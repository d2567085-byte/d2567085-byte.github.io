/* Иконки, которые рисуются заливкой, а не обводкой */
const FILLED_ICONS = new Set(['star', 'sparkle']);

/**
 * Инлайновая SVG-иконка.
 * @param {string} name  — ключ из ICON_PATHS
 * @param {string|number} [size] — размер (по умолчанию 1em — наследуется от font-size)
 * @param {string} [cls] — дополнительный класс
 */
function icon(name, size, cls) {
  const body = ICON_PATHS[name] || ICON_PATHS.info;
  const s = size ? (typeof size === 'number' ? size + 'px' : size) : '1em';
  const filled = FILLED_ICONS.has(name);
  return `<svg class="ico${cls ? ' ' + cls : ''}" width="${s}" height="${s}" viewBox="0 0 24 24" ` +
    `fill="${filled ? 'currentColor' : 'none'}" stroke="${filled ? 'none' : 'currentColor'}" ` +
    `stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

/* ============================================================
   ЛОГОТИП «ХозМастер»
   Фирменный знак: скруглённый квадрат (фирменный градиент),
   внутри — скрещённые молоток и отвёртка, образующие литеру
   «Х» (Хоз). Рукояти внизу, рабочие части вверху — знак
   читается и в 40 px в шапке, и в 16 px в фавиконе.
   ============================================================ */
let LOGO_UID = 0;

/**
 * Знак логотипа (без подписи).
 * @param {number} size — размер в px
 * @param {boolean} mono — монохромный вариант (подложка = currentColor)
 */
function logoMark(size = 40, mono = false) {
  const uid = ++LOGO_UID;
  const ink = '#fff';
  const badge = mono
    ? '<rect x="1.6" y="1.6" width="44.8" height="44.8" rx="13.6" fill="currentColor"/>'
    : `<defs><linearGradient id="hm-g${uid}" x1="4" y1="2" x2="44" y2="46" gradientUnits="userSpaceOnUse">
         <stop offset="0" stop-color="#0F766E"/><stop offset="0.45" stop-color="#2E7D32"/><stop offset="1" stop-color="#AF7C12"/>
       </linearGradient></defs>
       <rect x="1.6" y="1.6" width="44.8" height="44.8" rx="13.6" fill="url(#hm-g${uid})"/>
       <path d="M1.6 33.8 17.1 1.6h12.4L13.9 33.8Z" fill="#fff" opacity=".12"/>`;
  return `<svg class="logo-svg" width="${size}" height="${size}" viewBox="0 0 48 48" fill="none" role="img" aria-label="ХозМастер">
    ${badge}
    <g stroke="${ink}" stroke-linecap="round" stroke-linejoin="round">
      <!-- молоток: рукоять снизу-слева, головка сверху-справа -->
      <path d="M14.4 33.6 24.6 23.4" stroke-width="4.4"/>
      <rect x="21.3" y="17.2" width="11.6" height="7.4" rx="2.6" transform="rotate(45 27.1 20.9)" fill="${ink}" stroke="none"/>
      <!-- отвёртка: рукоять снизу-справа, жало сверху-слева -->
      <path d="M33.6 33.6 27.6 27.6" stroke-width="6.2"/>
      <path d="M26.2 26.2 18.4 18.4" stroke-width="3.2"/>
      <path d="M17.6 17.6 15.6 15.6" stroke-width="4.8"/>
    </g>
  </svg>`;
}

/**
 * Логотип целиком: знак + слово «ХозМастер».
 * @param {object} [opts] { size, mono, fontSize }
 */
function logoHtml(opts = {}) {
  const size = opts.size || 40;
  const cls = opts.mono ? ' logo-mono' : '';
  const fs = opts.fontSize ? `font-size:${opts.fontSize}px;` : '';
  return `<span class="mark${cls}"${fs ? ` style="${fs}"` : ''}>${logoMark(size, !!opts.mono)}</span>` +
         `<span class="wordmark">Хоз<em>Мастер</em></span>`;
}
